export function queryLocalBusinessDirectory({ location = '', category = '', limit = 50 }) {
  const locLower = (location || '').toLowerCase();
  const catLower = (category || '').toLowerCase();

  let filtered = LOCAL_BUSINESS_REGISTRY.filter(item => {
    const matchLoc = !locLower || item.location.toLowerCase().includes(locLower) || item.city.toLowerCase().includes(locLower) || locLower.includes('jamshedpur');
    const matchCat = !catLower || item.category.toLowerCase().includes(catLower) || catLower.includes(item.category.toLowerCase()) || catLower.includes('all') || catLower.includes('business') || catLower.includes('coaching') && item.category.includes('Coaching');
    return matchLoc && matchCat;
  });

  // If specific filter yielded few, return all matching the city
  if (filtered.length === 0) {
    filtered = LOCAL_BUSINESS_REGISTRY;
  }

  return filtered.slice(0, limit);
}
